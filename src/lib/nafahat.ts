/**
 * Calculates the Day of Year (1..366) from Gregorian date string YYYY-MM-DD
 */
export function getDayOfYear(dateStr: string = isoDate()): number {
  try {
    const parts = dateStr.split("-").map(Number);
    if (parts.length === 3) {
      const now = new Date(parts[0], parts[1] - 1, parts[2], 12, 0, 0);
      const start = new Date(parts[0], 0, 1, 12, 0, 0);
      const diff = now.getTime() - start.getTime();
      const oneDay = 1000 * 60 * 60 * 24;
      return Math.floor(diff / oneDay) + 1;
    }
  } catch (e) {}
  return 1;
}

