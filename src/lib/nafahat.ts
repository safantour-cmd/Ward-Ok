const SALAWAT_CACHE_KEY = "nafahat_custom_salawat_formulas";

export function getStoredSalawatFormulas(): SalawatFormula[] {
  try {
    const raw = localStorage.getItem(SALAWAT_CACHE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (e) {}
  return DEFAULT_SALAWAT_FORMULAS;
}

/**
 * Currently active/cached Salawat formulas list (starts with defaults or localStorage)
 */
export let SALAWAT_FORMULAS: SalawatFormula[] = getStoredSalawatFormulas();

export async function fetchGlobalSalawatFormulas(): Promise<SalawatFormula[]> {
  try {
    const snap = await getDoc(doc(dbFirestore, "global_config", "salawat_formulas"));
    if (snap.exists()) {
      const data = snap.data();
      if (data && Array.isArray(data.formulas) && data.formulas.length > 0) {
        const list = data.formulas as SalawatFormula[];
        try {
          localStorage.setItem(SALAWAT_CACHE_KEY, JSON.stringify(list));
        } catch (e) {}
        SALAWAT_FORMULAS = list;
        return list;
      }
    }
  } catch (err) {
    console.error("Failed to fetch global salawat formulas:", err);
  }
  return getStoredSalawatFormulas();
}

export function subscribeGlobalSalawatFormulas(cb: (formulas: SalawatFormula[]) => void): () => void {
  // initial call immediately from stored/cached
  cb(getStoredSalawatFormulas());

  try {
    const unsub = onSnapshot(
      doc(dbFirestore, "global_config", "salawat_formulas"),
      (snap) => {
        if (snap.exists()) {
          const data = snap.data();
          if (data && Array.isArray(data.formulas) && data.formulas.length > 0) {
            const list = data.formulas as SalawatFormula[];
            try {
              localStorage.setItem(SALAWAT_CACHE_KEY, JSON.stringify(list));
            } catch (e) {}
            SALAWAT_FORMULAS = list;
            cb(list);
            return;
          }
        }
        cb(getStoredSalawatFormulas());
      },
      (err) => {
        console.error("Failed to subscribe to global salawat formulas:", err);
      }
    );
    return unsub;
  } catch (err) {
    console.error("Error setting up salawat formulas subscription:", err);
    return () => {};
  }
}

export async function saveGlobalSalawatFormulas(formulas: SalawatFormula[]): Promise<void> {
  const normalized: SalawatFormula[] = formulas.map((f, idx) => ({
    day: idx + 1,
    title: (f.title || `صيغة اليوم ${idx + 1}`).trim(),
    arabicText: (f.arabicText || "").trim(),
    source: (f.source || "").trim(),
    merit: (f.merit || "").trim(),
    recommendedCount: Number(f.recommendedCount) > 0 ? Number(f.recommendedCount) : 100,
  }));

  try {
    localStorage.setItem(SALAWAT_CACHE_KEY, JSON.stringify(normalized));
  } catch (e) {}
  SALAWAT_FORMULAS = normalized;

  await setDoc(
    doc(dbFirestore, "global_config", "salawat_formulas"),
    {
      formulas: normalized,
      updated_at: new Date().toISOString(),
    },
    { merge: true }
  );

  // Dispatch custom event for immediate in-page reactivity across tabs/components
  if (typeof window !== "undefined") {
    window.dispatchEvent(new CustomEvent("nafahat-salawat-formulas-updated", { detail: normalized }));
  }
}

export async function updateSingleSalawatFormula(
  dayNumber: number,
  updatedData: Partial<SalawatFormula>
): Promise<void> {
  const current = getStoredSalawatFormulas();
  const updated = current.map((item) => {
    if (item.day === dayNumber) {
      return {
        ...item,
        ...updatedData,
        day: dayNumber,
      };
    }
    return item;
  });
  await saveGlobalSalawatFormulas(updated);
}

export async function swapSalawatFormulas(day1: number, day2: number): Promise<void> {
  if (day1 === day2) return;
  const current = [...getStoredSalawatFormulas()];
  const idx1 = current.findIndex((f) => f.day === day1);
  const idx2 = current.findIndex((f) => f.day === day2);

  if (idx1 !== -1 && idx2 !== -1) {
    const temp = { ...current[idx1] };
    current[idx1] = { ...current[idx2] };
    current[idx2] = temp;
    await saveGlobalSalawatFormulas(current);
  }
}

export async function moveSalawatFormula(fromIndex: number, toIndex: number): Promise<void> {
  if (fromIndex === toIndex) return;
  const current = [...getStoredSalawatFormulas()];
  if (fromIndex < 0 || fromIndex >= current.length || toIndex < 0 || toIndex >= current.length) {
    return;
  }
  const [moved] = current.splice(fromIndex, 1);
  current.splice(toIndex, 0, moved);
  await saveGlobalSalawatFormulas(current);
}

export async function resetSalawatFormulasToDefault(): Promise<void> {
  await saveGlobalSalawatFormulas(DEFAULT_SALAWAT_FORMULAS);
}

