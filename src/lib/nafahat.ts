/**
 * Returns the relevant Prophetic Gift(s) for a given date and Hijri day.
 * - Automatically guarantees that EVERY DAY of the year has its designated gift in order.
 * - Prioritizes exact date / rabi_day / day_of_year targets.
 * - Falls back to cyclic ordered list (Day 1, Day 2, etc.) so all users receive the gift seamlessly.
 */
export function getHadayaForDay(
  dateStr: string,
  rabiDay: number,
  adminHadayaList: GlobalHadayaItem[]
): Array<{
  id: string;
  title: string;
  hadithText: string;
  benefit: string;
  isAdminCreated?: boolean;
  targetBadge?: string;
  order?: number;
}> {
  const result: Array<{
    id: string;
    title: string;
    hadithText: string;
    benefit: string;
    isAdminCreated?: boolean;
    targetBadge?: string;
    order?: number;
  }> = [];

  const dayOfYear = getDayOfYear(dateStr);
  const activeList = adminHadayaList && adminHadayaList.length > 0 ? adminHadayaList : getDefaultGlobalHadayaList();

  // 1. Explicit matches for this exact calendar date / rabi day / day of year
  const explicitMatches = activeList.filter((item) => {
    if (item.target_type === "all") return true;
    if (item.target_type === "date" && item.target_value === dateStr) return true;
    if (item.target_type === "rabi_day" && String(item.target_value) === String(rabiDay)) return true;
    if (item.target_type === "day_of_year" && String(item.target_value) === String(dayOfYear)) return true;
    return false;
  });

  if (explicitMatches.length > 0) {
    explicitMatches.forEach((m, idx) => {
      result.push({
        id: m.id,
        title: m.title,
        hadithText: m.hadith_text,
        benefit: m.benefit,
        isAdminCreated: true,
        order: m.order || idx + 1,
        targetBadge:
          m.target_type === "all"
            ? "هدية نبوية مباركة (متاحة دائماً)"
            : m.target_type === "date"
            ? `هدية خاصة بتاريخ ${m.target_value}`
            : m.target_type === "rabi_day"
            ? `هدية اليوم ${m.target_value} من ربيع الأول`
            : `هدية اليوم المباركة (${m.target_value}) 🎁`,
      });
    });
    return result;
  }

  // 2. Ordered distribution across the year (cycles smoothly through the configured list)
  const targetIndex = (dayOfYear - 1) % activeList.length;
  const chosen = activeList[targetIndex] || activeList[0];

  if (chosen) {
    result.push({
      id: chosen.id,
      title: chosen.title,
      hadithText: chosen.hadith_text,
      benefit: chosen.benefit,
      isAdminCreated: true,
      order: chosen.order || targetIndex + 1,
      targetBadge: `هدية اليوم (${targetIndex + 1}) من الأنوار النبوية 🎁`,
    });
  }

  return result;
}

