/**
 * Swap two hadaya items in the ordered list
 */
export async function swapHadaya(indexA: number, indexB: number): Promise<void> {
  const current = await fetchGlobalHadaya();
  if (indexA < 0 || indexA >= current.length || indexB < 0 || indexB >= current.length) return;

  const next = [...current];
  const temp = next[indexA];
  next[indexA] = next[indexB];
  next[indexB] = temp;

  await saveGlobalHadayaList(next);
}

/**
 * Move a hadaya item from one position to another
 */
export async function moveHadaya(fromIndex: number, toIndex: number): Promise<void> {
  const current = await fetchGlobalHadaya();
  if (fromIndex < 0 || fromIndex >= current.length || toIndex < 0 || toIndex >= current.length) return;

  const next = [...current];
  const [moved] = next.splice(fromIndex, 1);
  next.splice(toIndex, 0, moved);

  await saveGlobalHadayaList(next);
}

